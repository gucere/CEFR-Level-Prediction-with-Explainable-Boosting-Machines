def mark_bands(axis):
    """Dotted lines between the CEFR bands (three course levels each) and the band names above the plot."""
    for boundary in (3.5, 6.5, 9.5, 12.5):
        axis.axvline(boundary, color='grey', linewidth=.5, linestyle=':')
    for position, band in zip((2, 5, 8, 11, 14), ('A1', 'A2', 'B1', 'B2', 'C1')):
        axis.text(position, 1.0, band, transform=axis.get_xaxis_transform(), ha='center', va='bottom', fontsize=8, color='grey')


def dimension_figure():
    shares = read(CV / 'cv_dimension_shares.csv', dtype={'output': str})
    source = 'CV'
    if shares is None or not shares.experiment.eq(f'classifier__{MAIN}').any():
        return
    table = shares[shares.experiment.eq(f'classifier__{MAIN}') & shares.task.eq('level') & shares.output.ne('overall')]
    figure, axis = plt.subplots(figsize=(6.2, 3.4))
    for dimension in DIMENSION_ORDER:
        line = table[table.dimension.eq(dimension)].assign(level=lambda frame: frame.output.astype(int)).sort_values('level')
        if line.empty:
            continue
        axis.plot(line.level, 100 * line.share_mean, marker='o', markersize=3, label=dimension.replace('_', ' '))
        axis.fill_between(line.level, 100 * (line.share_mean - line.share_standard_deviation),
                          100 * (line.share_mean + line.share_standard_deviation), alpha=.2)
    mark_bands(axis)
    axis.set(xlabel='Course level', ylabel='Share of contributions (%)', xticks=range(1, 16))
    axis.legend(fontsize=7, frameon=False, ncol=2)
    axis.set_title(f'Complexity dimensions in the main level classifier ({source}, mean ± SD)', fontsize=9, pad=14)
    save_figure(figure, 'figure_1_dimension_shares_by_level')


def tool_figure():
    """Tool shares per course-level output: CV mean ± SD when the cross-validation results exist, else the validation run."""
    shares = read(CV / 'cv_tool_shares.csv', dtype={'output': str})
    if shares is not None and shares.experiment.eq(f'classifier__{MAIN}').any():
        table = shares[shares.experiment.eq(f'classifier__{MAIN}') & shares.task.eq('level') & shares.output.str.isdigit()]
        source, value, spread = 'CV, mean ± SD', 'share_mean', 'share_standard_deviation'
    else:
        tools = read(LEVEL / '3_Feature_Contributions/0_All_Experiments/tool_contributions_level_all_experiments.csv', dtype={'output': str})
        if tools is None:
            return
        table = tools[tools.experiment.eq(f'classifier__{MAIN}') & tools.output.str.isdigit()]
        source, value, spread = 'validation', 'share', None
    figure, axis = plt.subplots(figsize=(6.2, 3.4))
    for tool in TOOLS:
        line = table[table.tool.eq(tool)].assign(level=lambda frame: frame.output.astype(int)).sort_values('level')
        if line.empty:
            continue
        axis.plot(line.level, 100 * line[value], marker='o', markersize=3, label=tool)
        if spread:
            axis.fill_between(line.level, 100 * (line[value] - line[spread]), 100 * (line[value] + line[spread]), alpha=.2)
    axis.set(xlabel='Course level', ylabel='Share of contributions (%)', xticks=range(1, 16))
    axis.legend(fontsize=7, frameon=False, ncol=2)
    mark_bands(axis)
    axis.set_title(f'Feature groups (tools) in the main level classifier ({source})', fontsize=9, pad=14)
    save_figure(figure, 'figure_2_tool_shares_by_level')


def confusion_figure():
    confusion = read(CV / 'cv_confusion_matrices.csv', dtype={'true_label': str, 'predicted_label': str})
    if confusion is None or not confusion.experiment.eq(f'classifier__{MAIN}').any():
        return
    figure, axes = plt.subplots(1, 2, figsize=(9, 4), gridspec_kw={'width_ratios': [3, 1.4]})
    for axis, target in zip(axes, ('level', 'cefr')):
        table = confusion[confusion.experiment.eq(f'classifier__{MAIN}') & confusion.evaluated_target.eq(target)]
        labels = sorted(table.true_label.unique(), key=lambda label: (len(label), label))
        matrix = table.pivot_table(index='true_label', columns='predicted_label', values='percentage_of_true_label', fill_value=0).reindex(
            index=labels, columns=labels, fill_value=0)
        axis.imshow(matrix.to_numpy(), cmap='Blues', vmin=0, vmax=100)
        axis.set(xticks=range(len(labels)), yticks=range(len(labels)), xlabel='Predicted', ylabel='True',
                 title='Course level' if target == 'level' else 'CEFR (summed level probabilities)')
        axis.set_xticklabels(labels, fontsize=6 if target == 'level' else 8)
        axis.set_yticklabels(labels, fontsize=6 if target == 'level' else 8)
        for (row, column), value in np.ndenumerate(matrix.to_numpy()):
            if value >= (1 if target == 'level' else .1):
                axis.text(column, row, f'{value:.0f}' if target == 'level' else f'{value:.1f}', ha='center', va='center',
                          fontsize=5 if target == 'level' else 7, color='white' if value > 60 else 'black')
    figure.suptitle('Main level classifier, 10-fold CV pooled (% of each true class)', fontsize=9)
    save_figure(figure, 'figure_3_confusion_matrices')


