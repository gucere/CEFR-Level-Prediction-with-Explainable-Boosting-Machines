def markdown(table):
    cells = table.astype(object).where(table.notna(), '').astype(str)
    lines = ['| ' + ' | '.join(map(str, cells.columns)) + ' |', '|' + '---|' * len(cells.columns)]
    return '\n'.join(lines + ['| ' + ' | '.join(row) + ' |' for row in cells.to_numpy()])


def latex(table, caption, label):
    escape = lambda text: str(text).replace('_', r'\_').replace('%', r'\%').replace('&', r'\&').replace('±', r'$\pm$').replace('−', '--')
    cells = table.astype(object).where(table.notna(), '').astype(str)
    lines = [r'\begin{table}[t]', r'\centering', r'\small', r'\begin{tabular}{l' + 'r' * (len(cells.columns) - 1) + '}', r'\toprule',
             ' & '.join(map(escape, cells.columns)) + r' \\', r'\midrule']
    lines += [' & '.join(map(escape, row)) + r' \\' for row in cells.to_numpy()]
    return '\n'.join(lines + [r'\bottomrule', r'\end{tabular}', rf'\caption{{{escape(caption)}}}', rf'\label{{{label}}}', r'\end{table}'])


class Report:
    def __init__(self):
        self.sections = []

    def add(self, name, caption, table, display=None):
        TABLES.mkdir(parents=True, exist_ok=True)
        table.to_csv(TABLES / f'{name}.csv', index=False, encoding='utf-8-sig')
        self.sections.append((name, caption, table if display is None else display))
        log(f'  table {name}: {len(table)} rows')

    def write(self):
        text = ['# Paper tables', '', 'Generated by `paper_tables.py`; the CSV files hold the unrounded values.', '']
        tex = ['% Generated by paper_tables.py; needs \\usepackage{booktabs}.', '']
        for name, caption, table in self.sections:
            text += [f'## {name}', '', caption, '', markdown(table), '']
            tex += [latex(table, caption, f'tab:{name}'), '']
        if NOTES:
            text += ['## Not yet available', ''] + [f'- {note}' for note in NOTES] + ['']
        (TABLES / 'paper_tables.md').write_text('\n'.join(text), encoding='utf-8')
        (TABLES / 'paper_tables.tex').write_text('\n'.join(tex), encoding='utf-8')


def save_figure(figure, name):
    FIGURES.mkdir(parents=True, exist_ok=True)
    for suffix in ('png', 'pdf'):
        figure.savefig(FIGURES / f'{name}.{suffix}', dpi=200, bbox_inches='tight', metadata={'CreationDate': None} if suffix == 'pdf' else None)
    plt.close(figure)
    log(f'  figure {name}')


