def data_table(report):
    manifest = wf.read_json(wf.SHARED / 'dataset_manifest.json')
    splits = pd.read_csv(wf.SHARED / 'splits.csv', dtype={'learner_id': str, 'cefr_level': str})
    data = wf.resolve_manifest_path(manifest['data_directory']) / 'feature_dataframe.parquet'
    with duckdb.connect() as connection:
        words = connection.execute(f'SELECT text_id, "complexity__LCA__wordtokens" AS words FROM read_parquet({wf.literal(data)})').df()
    splits = splits.merge(words, on='text_id', how='left', validate='one_to_one')
    rows = []
    for cefr, group in splits.groupby('cefr_level', sort=True):
        row = {'CEFR': cefr, 'Levels': f'{group.level.min()}–{group.level.max()}'}
        row.update({f'{split.capitalize()} texts': int(group.split.eq(split).sum()) for split in ('train', 'validation', 'test')})
        row.update({'Learners': group.learner_id.nunique(), 'Median words': int(group.words.median()),
                    'Texts under 50 words': f'{100 * group.words.lt(50).mean():.0f}%'})
        rows.append(row)
    total = {'CEFR': 'All', 'Levels': '1–15', **{f'{split.capitalize()} texts': int(splits.split.eq(split).sum()) for split in ('train', 'validation', 'test')},
             'Learners': splits.learner_id.nunique(), 'Median words': int(splits.words.median()),
             'Texts under 50 words': f'{100 * splits.words.lt(50).mean():.0f}%'}
    report.add('table_1_data', 'EFCAMDAT texts per CEFR band and learner-disjoint split (70/15/15).', pd.DataFrame(rows + [total]))


