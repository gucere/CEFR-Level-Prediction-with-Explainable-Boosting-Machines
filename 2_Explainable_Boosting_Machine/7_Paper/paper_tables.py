def plus_minus(mean, deviation, digits=3):
    if pd.isna(mean):
        return ''
    return f'{mean:.{digits}f}' + (f' ± {deviation:.{digits}f}' if pd.notna(deviation) else '')


def read(path, **options):
    if not path.is_file():
        NOTES.append(f'missing {path.relative_to(wf.BASE)}')
        return None
    return pd.read_csv(path, **options)


