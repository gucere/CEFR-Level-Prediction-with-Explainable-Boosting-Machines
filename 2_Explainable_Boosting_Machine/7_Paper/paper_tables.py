def task_rows(table, label_of):
    rows = []
    for _, row in table.iterrows():
        values = {name: f'{row[column]:.3f}' for column, name in TASK_METRICS.items() if column in row and pd.notna(row[column])}
        rows.append({'Feature set': LABELS.get(row.family, row.family), 'Model': row.algorithm, 'Evaluated on': label_of(row), **values})
    return rows


def topic_table(report):
    """Performance on writing tasks seen and not seen in training (models trained on half of each level's tasks),
    averaged over both halves, next to the models trained on all tasks."""
    results = read(VALIDITY / '1_Topic_Check/topic_check_results.csv')
    if results is None:
        return
    metrics = [column for column in TASK_METRICS if column in results]
    table = results.groupby(['family', 'algorithm', 'model', 'topics'], sort=False, as_index=False)[metrics].mean()
    # The all-task model's seen and unseen halves swap between the two directions, so their mean is its overall result.
    table = table[table.model.eq('topic_restricted') | table.topics.eq('seen_topics')]
    names = {('topic_restricted', 'seen_topics'): 'seen tasks', ('topic_restricted', 'unseen_topics'): 'unseen tasks',
             ('main_model_all_topics', 'seen_topics'): 'all tasks in training (main run)'}
    report.add('table_9_topic_check', 'Topic check: models trained on the training texts of 4 of the 8 writing tasks per level '
               '(then the other 4), evaluated on validation texts of tasks seen and not seen in training (mean of both halves), '
               'next to the same models trained on all tasks.', table,
               pd.DataFrame(task_rows(table, lambda row: names[(row.model, row.topics)])))


def task_table(report):
    summary, folds = read(VALIDITY / '3_Leave_One_Task_Out/task_check_summary.csv'), read(VALIDITY / '3_Leave_One_Task_Out/task_check_folds.csv')
